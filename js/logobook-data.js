function renderLogobook() {
  const container = document.getElementById('logobook-content');
  if (!container || !LOGOBOOK_DATA) return;
  
  let html = '';
  
  const sectionColors = [
    '#6366f1', '#8b5cf6', '#d4af37', '#f43f5e', '#3b82f6', '#06b6d4', '#f59e0b', '#10b981'
  ];

  LOGOBOOK_DATA.forEach((sec, idx) => {
    const color = sectionColors[idx % sectionColors.length];
    html += `
      <div class="lb-section-hero" id="${sec.id}">
        <div class="lb-section-hero-content">
          <div class="lb-section-index">${sec.index}</div>
          <h2>${sec.title}</h2>
          <p>${sec.desc}</p>
        </div>
      </div>
      <div class="lb-section-wrapper" data-title="${sec.title}" style="border: 1px solid ${color}40; padding: var(--space-4); margin-bottom: var(--space-8); border-radius: var(--radius-lg);">
        <div class="lb-cards-grid">
    `;
    
    sec.cards.forEach(card => {
      const fieldsHtml = card.fields.map(f => `
        <div>
          <dt>${f.key}</dt>
          <dd>${f.value}</dd>
        </div>
      `).join('');
      
      html += `
        <article class="lb-page-card" id="${card.id}">
          <div class="lb-page-topline">
          </div>
          <h3>${card.title}</h3>
          <dl class="lb-page-fields">
            ${fieldsHtml}
          </dl>
          <div class="lb-visual-placeholder">
            <div class="lb-visual-kicker">${card.visual.kicker}</div>
            <p>${card.visual.desc}</p>
          </div>
        </article>
      `;
    });
    
    html += `</div></div>`;
  });
  
  container.innerHTML = html;
  container.style.display = 'block';
  container.style.alignItems = '';
  container.style.justifyContent = '';
  
  if (typeof renderUploadZones === 'function') renderUploadZones();
  if (typeof injectCommentPanel === 'function') injectCommentPanel();
  
  // Apply GSAP animation if available
  if (window.gsap && window.ScrollTrigger) {
    gsap.utils.toArray('.lb-page-card').forEach(card => {
      gsap.from(card, {
        scrollTrigger: {
          trigger: card,
          start: "top 90%",
          toggleActions: "play none none reverse"
        },
        y: 30,
        opacity: 0,
        duration: 0.5,
        ease: "power2.out"
      });
    });

    // Breadcrumb updates based on active section
    gsap.utils.toArray('.lb-section-wrapper').forEach(wrapper => {
      ScrollTrigger.create({
        trigger: wrapper,
        start: "top center",
        end: "bottom center",
        onToggle: self => {
          if (self.isActive) {
            const title = wrapper.getAttribute('data-title');
            const bc = document.getElementById('breadcrumbCurrent');
            if (bc) bc.innerHTML = `LOGOBOOK / <span style="color:var(--color-primary);">${title}</span>`;
          }
        }
      });
    });
  }
}

// Render after a short delay to keep UI smooth
window.addEventListener('DOMContentLoaded', () => {
  if (document.getElementById('logobook-content')) {
    setTimeout(renderLogobook, 100);
  }
});
